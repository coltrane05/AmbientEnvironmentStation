uint16_t get_glyph_id(char character) 
{
    uint8_t glyph_id;
    if ((uint8_t)character >= cmaps[0].range_start && (uint8_t)character <= cmaps[0].range_start + cmaps[0].range_length)
    {
        glyph_id = cmaps[0].glyph_id_start + cmaps[0].glyph_id_ofs_list[(character - cmaps[0].range_start)];
    }
    else if ((uint8_t)character >= cmaps[1].range_start && (uint8_t)character <= cmaps[1].range_start + cmaps[1].range_length)
    {
        glyph_id = cmaps[1].glyph_id_start + (character - cmaps[1].range_start);
    }
    else if ((uint8_t)character >= cmaps[2].range_start && (uint8_t)character <= cmaps[2].range_start + cmaps[2].range_length)
    {
        glyph_id = cmaps[2].glyph_id_start + (character - cmaps[2].range_start);
    }

    return glyph_id;
}

uint8_t * get_glyph_dimensions(char character)
{
    static uint8_t dimensions[2];
    uint16_t glyph_id = get_glyph_id(character);
    dimensions[0] = glyph_dsc[glyph_id].box_w;
    dimensions[1] = glyph_dsc[glyph_id].box_h;

    return dimensions;
}

uint16_t * get_glyph_offsets(char character)
{
    static uint16_t offsets[4];
    uint16_t glyph_id = get_glyph_id(character);

    offsets[0] = glyph_dsc[glyph_id].adv_w;
    offsets[1] = glyph_dsc[glyph_id].box_h;
    offsets[2] = glyph_dsc[glyph_id].ofs_x;
    offsets[3] = glyph_dsc[glyph_id].ofs_y;

    return offsets;
}

uint16_t * generate_character_display_data(char character, uint16_t color, uint16_t bg_color)
{
    uint8_t glyph_id = get_glyph_id(character);
    uint8_t character_width = glyph_dsc[glyph_id].box_w;
    uint8_t character_height = glyph_dsc[glyph_id].box_h;
    uint16_t num_glyph_bits = character_height * character_width;
    uint8_t num_glyph_bytes;

    if (num_glyph_bits % 8 == 0)
    {
        num_glyph_bytes = num_glyph_bits / 8;
    }
    else
    {
        num_glyph_bytes = (num_glyph_bits / 8) + 1;
    }

    // Static buffer sized for the largest glyph in the font (21x14 = 294 pixels)
    static uint16_t character_display_data[294];
    uint16_t bit_idx = 0;
    uint16_t bitmap_idx = glyph_dsc[glyph_id].bitmap_index;

    for (uint8_t i = 0; i < num_glyph_bytes; i++)
    {
        for (uint8_t j = 0; j < 8; j++)
        {
            if (bit_idx < num_glyph_bits)
            {
                if (glyph_bitmap[bitmap_idx] & (0x80 >> j)) 
                {
                    character_display_data[bit_idx] = color;
                }
                else
                {
                    character_display_data[bit_idx] = bg_color;
                }
                bit_idx++;
            }
            else
            {
                break;
            }
        }
        bitmap_idx++;
    }

    return character_display_data;
}